import { spawnSync } from "node:child_process";
import { cpSync, mkdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const appDir = path.join(root, "app");
const outDir = path.join(appDir, "dist-pages");
const repo = "strum-us/dotnote-demo";
const pagesUrl = "https://strum-us.github.io/dotnote-demo/";

function run(command, args, opts = {}) {
  const result = spawnSync(command, args, { stdio: "inherit", ...opts });
  if (result.status !== 0) process.exit(result.status ?? 1);
}

function capture(command, args, opts = {}) {
  const result = spawnSync(command, args, { encoding: "utf8", ...opts });
  return { status: result.status ?? 1, stdout: result.stdout ?? "", stderr: result.stderr ?? "" };
}

console.log("Building the Pages demo…");
rmSync(outDir, { recursive: true, force: true });
run("pnpm", ["exec", "vite", "build"], {
  cwd: appDir,
  env: {
    ...process.env,
    DOTNOTE_PAGES_BASE: "/dotnote-demo/",
    DOTNOTE_PAGES_OUT: "dist-pages",
    VITE_API_ORIGIN: "https://demo.dotnote.cloud",
  },
});

const indexHtml = readFileSync(path.join(outDir, "index.html"));
writeFileSync(path.join(outDir, "404.html"), indexHtml);
mkdirSync(path.join(outDir, "entry-sample"), { recursive: true });
writeFileSync(path.join(outDir, "entry-sample", "index.html"), indexHtml);
writeFileSync(path.join(outDir, ".nojekyll"), "");
writeFileSync(
  path.join(outDir, "README.md"),
  `# Dotnote demo

Static build published to [GitHub Pages](${pagesUrl}).

The page is this build. Notes and accounts stay on the Dotnote demo worker at \`demo.dotnote.cloud\`.

Open ${pagesUrl}entry-sample

Generated by \`pnpm deploy:pages-demo\`. Don't edit this repository by hand.
`,
);

const work = path.join(tmpdir(), `dotnote-demo-pages-${Date.now()}`);
mkdirSync(work, { recursive: true });

const exists = capture("gh", ["repo", "view", repo, "--json", "name"]);
if (exists.status !== 0) {
  console.log(`Creating ${repo}…`);
  run("gh", [
    "api",
    "--method",
    "POST",
    "/orgs/strum-us/repos",
    "-f",
    "name=dotnote-demo",
    "-f",
    "description=Dotnote demo on GitHub Pages. The app is static; notes stay on the Cloudflare demo.",
    "-F",
    "private=false",
    "-F",
    "has_wiki=false",
  ]);
  run("git", ["init", "-b", "main"], { cwd: work });
  run("git", ["remote", "add", "origin", `https://github.com/${repo}.git`], { cwd: work });
} else {
  run("git", ["clone", "--depth", "1", `https://github.com/${repo}.git`, work]);
  for (const entry of ["index.html", "404.html", "assets", "entry-sample", "logo.svg", "README.md", ".nojekyll"]) {
    rmSync(path.join(work, entry), { recursive: true, force: true });
  }
}

cpSync(outDir, work, { recursive: true });
run("git", ["add", "-A"], { cwd: work });
const dirty = capture("git", ["status", "--porcelain"], { cwd: work });
if (!dirty.stdout.trim() && exists.status === 0) {
  console.log("Pages demo is already up to date.");
} else {
  run("git", ["commit", "-m", "Publish the Dotnote demo."], { cwd: work });
  run("git", ["push", "-u", "origin", "HEAD"], { cwd: work });
}

const pages = capture("gh", ["api", `repos/${repo}/pages`]);
if (pages.status !== 0) {
  console.log("Enabling GitHub Pages…");
  const enabled = spawnSync(
    "gh",
    ["api", "--method", "POST", `repos/${repo}/pages`, "--input", "-"],
    {
      input: JSON.stringify({ build_type: "legacy", source: { branch: "main", path: "/" } }),
      stdio: ["pipe", "inherit", "inherit"],
    },
  );
  if (enabled.status !== 0) process.exit(enabled.status ?? 1);
}

console.log(`Demo: ${pagesUrl}entry-sample`);
